let activeCat = "ao-thun";

function render(cat, limit = 8) {
  const grid = document.getElementById("productGrid");
  const btn = document.getElementById("loadMoreBtn");
  const list = products[cat] || [];
  grid.innerHTML = "";

  list.slice(0, limit).forEach((p) => {
    grid.innerHTML += `
                <div class="card">
                    <a href="product-detail.html?cat=${cat}&name=${encodeURIComponent(
      p.name
    )}" style="text-decoration: none; color: inherit;">
                        <div class="img-box"><img src="images/products/${
                          p.img
                        }"></div>
                        <div class="name">${p.name}</div>
                        <div class="stars">★★★★★</div>
                        <div class="price">${p.price}</div>
                    </a>
                </div>`;
  });
  list.length > limit
    ? btn.classList.remove("hidden")
    : btn.classList.add("hidden");
}

function setCategory(cat, el) {
  document
    .querySelectorAll(".cat-item")
    .forEach((i) => i.classList.remove("active"));
  el.classList.add("active");
  activeCat = cat;
  render(cat, 8);
}

function handleLoadMore() {
  render(activeCat, 999);
}

window.onload = () => render("ao-thun", 8);

let currentCat = "ao-thun";
let currentProduct = null;

function initCatNav() {
  const nav = document.getElementById("catNav");
  if (!nav) return;
  nav.innerHTML = "";
  categories.forEach((c) => {
    nav.innerHTML += `
                <div class="cat-item ${
                  c.id === currentCat ? "active" : ""
                }" onclick="setCategory('${c.id}', this)">
                    <img src="images/icons/${c.icon}"><span>${c.name}</span>
                </div>`;
  });
}

function setCategory(cat, el) {
  document
    .querySelectorAll(".cat-item")
    .forEach((i) => i.classList.remove("active"));
  if (el) el.classList.add("active");
  currentCat = cat;
  renderSimilarProducts(currentCat, 4);
}

function renderSimilarProducts(cat, limit = 4) {
  const grid = document.getElementById("similarProductsGrid");
  const btn = document.getElementById("loadMoreBtnSimilar");
  if (!grid) return;

  const list = products[cat] || [];
  grid.innerHTML = "";
  const filteredList = list.filter((p) => p.name !== currentProduct?.name);

  filteredList.slice(0, limit).forEach((p) => {
    grid.innerHTML += `
                <div class="similar-card" onclick="loadProductDetail('${cat}', '${p.name}')">
                    <div class="img-box"><img src="images/products/${p.img}"></div>
                    <div class="heart"></div>
                    <div class="name">${p.name}</div>
                    <div class="price">${p.price}</div>
                </div>`;
  });

  if (btn) {
    if (filteredList.length > limit) {
      btn.classList.remove("hidden");
      btn.style.display = "block";
    } else {
      btn.classList.add("hidden");
      btn.style.display = "none";
    }
  }
}


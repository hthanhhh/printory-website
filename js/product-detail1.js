// 1. Hàm đổi ảnh chính khi click vào thumbnail
function changeMainImage(src, el) {
  document.getElementById("productMainImage").src = src;
  document
    .querySelectorAll(".thumb-item")
    .forEach((item) => item.classList.remove("active"));
  if (el) el.classList.add("active");
}

// 2. Sửa lại hàm load chi tiết sản phẩm để hiện ảnh mặt trước/sau
function loadProductDetail(category, productName) {
  const product = products[category].find((p) => p.name === productName);
  if (product) {
    currentProduct = product;
    currentCat = category;

    document.getElementById(
      "productMainImage"
    ).src = `images/products/${product.img}`;
    document.getElementById("productName").innerText =
      product.name.toUpperCase();
    document.getElementById("productPrice").innerText = product.price;

    // Xử lý ảnh phụ (Thumbnails)
    const thumbContainer = document.getElementById("thumbContainer");
    thumbContainer.innerHTML = "";
    if (product.backImg) {
      thumbContainer.innerHTML = `
                <div class="thumb-item active" onclick="changeMainImage('images/products/${product.img}', this)">
                    <img src="images/products/${product.img}">
                </div>
                <div class="thumb-item" onclick="changeMainImage('images/products/${product.backImg}', this)">
                    <img src="images/products/${product.backImg}">
                </div>`;
    }

    // Cập nhật mô tả & tương tự (giữ nguyên code cũ của bạn bên dưới...)
    const infoSections = document.querySelectorAll(".info-section");
    if (infoSections[0])
      infoSections[0].querySelector("p").innerText = product.desc;
    renderSimilarProducts(category, 4);
    window.scrollTo({ top: 0, behavior: "smooth" });
  }
}

window.onload = () => {
  initCatNav();
  setupOptions(); // Kích hoạt sự kiện nhuộm màu/size

  // 1. Lấy các tham số từ URL
  const urlParams = new URLSearchParams(window.location.search);
  const catParam = urlParams.get("cat"); // Lấy 'cat'
  const nameParam = urlParams.get("name"); // Lấy 'name'

  // 2. Nếu có tham số trên URL thì load sản phẩm đó, không thì load mặc định
  if (catParam && nameParam) {
    // Giải mã tên sản phẩm từ URL
    const decodedName = decodeURIComponent(nameParam);
    loadProductDetail(catParam, decodedName);
  } else {
    // Load mặc định nếu vào trực tiếp trang chi tiết
    loadProductDetail("ao-thun", "Áo thun trắng Unisex");
  }
};

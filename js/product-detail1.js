function setupOptions() {
  const colorOpt = document.querySelector(".color-options");
  const sizeOpt = document.querySelector(".size-options");

  if (colorOpt) {
    colorOpt.onclick = (e) => {
      if (e.target.tagName === "SPAN") {
        colorOpt
          .querySelectorAll("span")
          .forEach((s) => s.classList.remove("selected"));
        e.target.classList.add("selected");
      }
    };
  }
  if (sizeOpt) {
    sizeOpt.onclick = (e) => {
      if (e.target.tagName === "SPAN") {
        sizeOpt
          .querySelectorAll("span")
          .forEach((s) => s.classList.remove("selected"));
        e.target.classList.add("selected");
      }
    };
  }
}


// HÀM CHÍNH: THÊM VÀO GIỎ HÀNG
function addToCart() {
    // 1. Lấy thông tin cơ bản
    const name = document.getElementById('productName').innerText;
    const priceText = document.getElementById('productPrice').innerText;
    const price = parseInt(priceText.replace(/\D/g, '')); // Lấy số: 200000
    const image = document.getElementById('productMainImage').getAttribute('src');
    const quantity = parseInt(document.getElementById('quantityInput').value);

    // 2. Lấy Màu sắc đang chọn
    const selectedColorEl = document.querySelector('#colorOptions span.selected');
    const color = selectedColorEl ? selectedColorEl.getAttribute('data-color') : "Trắng";

    // 3. Lấy Size đang chọn
    const selectedSizeEl = document.querySelector('#sizeOptions span.selected');
    const size = selectedSizeEl ? selectedSizeEl.innerText : "M";

    // 4. Lấy Ảnh thiết kế (Nếu bạn có dùng trang thiết kế đè lên)
    // Giả sử sau khi thiết kế xong bạn lưu ảnh vào 1 id là 'designLayer'
    const designLayer = document.getElementById('designLayer');
    const design = designLayer ? designLayer.getAttribute('src') : "";

    // 5. Tạo đối tượng sản phẩm
    const newItem = {
        id: Date.now(), // Tạo ID duy nhất
        name: name,
        price: price,
        image: image,
        size: size,
        color: color,
        quantity: quantity,
        design: design
    };

    // 6. Lưu vào LocalStorage
    // Lấy giỏ hàng cũ về
    let cart = JSON.parse(localStorage.getItem('printoryCart')) || [];

    // Kiểm tra xem sản phẩm cùng loại (tên, size, màu, thiết kế) đã có chưa
    const existingIndex = cart.findIndex(item => 
        item.name === newItem.name && 
        item.size === newItem.size && 
        item.color === newItem.color &&
        item.design === newItem.design
    );

    if (existingIndex !== -1) {
        // Nếu có rồi thì tăng số lượng lên
        cart[existingIndex].quantity += quantity;
    } else {
        // Nếu chưa có thì thêm mới
        cart.push(newItem);
    }

    // Lưu lại mảng mới vào localStorage
    localStorage.setItem('printoryCart', JSON.stringify(cart));

    // 7. Thông báo và chuyển hướng (tùy chọn)
    alert("Đã thêm " + quantity + " sản phẩm vào giỏ hàng!");
}

// Gán sự kiện khi trang web load xong
document.addEventListener('DOMContentLoaded', function() {
    // Tìm nút thêm vào giỏ hàng
    const addCartBtn = document.querySelector('.btn-add-cart');
    if (addCartBtn) {
        addCartBtn.addEventListener('click', function(e) {
            e.preventDefault(); // Ngăn việc chuyển trang ngay lập tức của thẻ <a>
            addToCart();
            // Nếu muốn thêm xong nhảy vào giỏ hàng luôn thì bỏ comment dòng dưới:
            // window.location.href = 'cart.html'; 
        });
    }

    // Logic để chọn Size/Màu (Nếu bạn chưa viết)
    setupOptionSelection();
});

function setupOptionSelection() {
    // Chọn màu
    document.querySelectorAll('#colorOptions span').forEach(span => {
        span.addEventListener('click', function() {
            document.querySelectorAll('#colorOptions span').forEach(s => s.classList.remove('selected'));
            this.classList.add('selected');
        });
    });

    // Chọn size
    document.querySelectorAll('#sizeOptions span').forEach(span => {
        span.addEventListener('click', function() {
            document.querySelectorAll('#sizeOptions span').forEach(s => s.classList.remove('selected'));
            this.classList.add('selected');
        });
    });
}